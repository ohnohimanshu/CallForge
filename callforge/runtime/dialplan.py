"""Generate Asterisk dialplan snippets for deployed agents."""

from __future__ import annotations

import os
from pathlib import Path

from callforge.store.models import AgentRecord

AUDIOSOCKET_HOST = os.getenv("AUDIOSOCKET_HOST", "127.0.0.1")

HEADER = """; AUTO-GENERATED by CallForge — do not edit by hand.
; Reload with: asterisk -rx "dialplan reload"
; Included from extensions.conf via #include extensions_agents.conf

[from-internal]
"""


def render_agent_extension(agent: AgentRecord, host: str | None = None) -> str:
    if not agent.port:
        return ""
    ext = agent.extension
    port = agent.port
    name = agent.name.replace(")", "").replace("(", "")
    audio_host = host or os.getenv("AUDIOSOCKET_HOST", "127.0.0.1")
    
    # Collect all dialable targets for this agent:
    # 1. Internal extension (e.g. 2000)
    # 2. Public carrier phone number (e.g. +14158002481, 14158002481, 4158002481)
    targets = [ext]
    if agent.phone_number:
        p = agent.phone_number.strip()
        clean = p.lstrip("+")
        for num in (p, clean, f"+{clean}"):
            if num not in targets:
                targets.append(num)
        if len(clean) == 11 and clean.startswith("1"):
            ten_digit = clean[1:]
            if ten_digit not in targets:
                targets.append(ten_digit)

    chunks = []
    for target in targets:
        chunks.append(f"""\
; Agent: {name} ({agent.id}) | Target: {target}
exten => {target},1,NoOp(CallForge agent '{name}' on {target})
 same => n,Answer()
 same => n,Wait(0.3)
 same => n,ExecIf($["${{CALL_UUID}}" = ""]?Set(CALL_UUID=${{SHELL(cat /proc/sys/kernel/random/uuid | tr -d '\\n')}}))
 same => n,Set(CF_AGENT_ID={agent.id})
 same => n,System(mkdir -p -m 777 /etc/asterisk/calls /tmp/callforge_calls 2>/dev/null && (test -s /etc/asterisk/calls/${{CALL_UUID}}.callerid || echo "${{CALLERID(num)}}" > /etc/asterisk/calls/${{CALL_UUID}}.callerid) && (test -s /tmp/callforge_calls/${{CALL_UUID}}.callerid || echo "${{CALLERID(num)}}" > /tmp/callforge_calls/${{CALL_UUID}}.callerid) && chmod 666 /etc/asterisk/calls/${{CALL_UUID}}.callerid /tmp/callforge_calls/${{CALL_UUID}}.callerid 2>/dev/null || true)
 same => n,AudioSocket(${{CALL_UUID}},{audio_host}:{port})
 same => n,Set(HANDOFF_FILE=/etc/asterisk/handoff/${{CALL_UUID}}.target)
 same => n,Set(TARGET=${{SHELL(test -f ${{HANDOFF_FILE}} && (cat ${{HANDOFF_FILE}} | tr -d '\\n') && rm -f ${{HANDOFF_FILE}})}})
 same => n,GotoIf($["${{TARGET}}" != ""]?do_handoff:do_hangup)
 same => n(do_handoff),NoOp(CallForge human handoff forwarding to extension ${{TARGET}})
 same => n,Goto(internal,${{TARGET}},1)
 same => n(do_hangup),System(rm -f /etc/asterisk/calls/${{CALL_UUID}}.callerid /tmp/callforge_calls/${{CALL_UUID}}.callerid 2>/dev/null || true)
 same => n,Hangup()

exten => {target},n,NoOp(AudioSocket failed for agent '{name}' on {target})
 same => n,Playback(tt-somethingwrong)
 same => n,Hangup()
""")
    return "\n".join(chunks) + "\n"



def write_agents_dialplan(agents: list[AgentRecord], output_path: Path, host: str | None = None) -> Path:
    """Write extensions_agents.conf for all deployed agents."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    body = HEADER
    deployed = [a for a in agents if a.status == "deployed" and a.port]
    if not deployed:
        body += "; (no deployed agents)\n"
    else:
        for agent in sorted(deployed, key=lambda a: a.extension):
            body += render_agent_extension(agent, host=host)
    output_path.write_text(body, encoding="utf-8")
    return output_path
