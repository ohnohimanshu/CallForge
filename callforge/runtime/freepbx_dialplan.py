"""Generate FreePBX Method 1 (Direct AudioSocket) dialplan snippets.

FreePBX owns phones, trunks, and routing. CallForge only exposes AudioSocket
TCP listeners. Operators paste the generated context into:

  /etc/asterisk/extensions_custom.conf

then point a Custom Destination / Inbound Route at it.
"""

from __future__ import annotations

import os
from pathlib import Path
from callforge.store.models import AgentRecord

# Host FreePBX uses to reach CallForge AudioSocket + HTTP APIs.
# Prefer FREEPBX_AUDIOSOCKET_HOST, then AUDIOSOCKET_HOST, then localhost.
DEFAULT_HOST = (
    os.getenv("FREEPBX_AUDIOSOCKET_HOST")
    or os.getenv("AUDIOSOCKET_HOST")
    or "127.0.0.1"
)
DEFAULT_API_BASE = os.getenv("FREEPBX_API_BASE") or os.getenv("CALLFORGE_PUBLIC_URL") or ""


def _api_base(host: str, api_base: str | None = None) -> str:
    if api_base:
        return api_base.rstrip("/")
    if DEFAULT_API_BASE:
        return DEFAULT_API_BASE.rstrip("/")
    # When FreePBX and CallForge share a LAN, HTTP API is on the same host:8080.
    return f"http://{host}:8080"


def render_agent_freepbx_context(
    agent: AgentRecord,
    host: str | None = None,
    api_base: str | None = None,
    handoff_context: str = "from-internal",
) -> str:
    """Render one FreePBX custom context that bridges a call into CallForge."""
    if not agent.port:
        return ""

    audio_host = host or DEFAULT_HOST
    base = _api_base(audio_host, api_base)
    ext = agent.extension.strip()
    port = agent.port
    name = agent.name.replace(")", "").replace("(", "").replace('"', "")
    agent_id = agent.id
    handoff_ext = (agent.handoff_extension or "1001").strip()

    return f"""\
; =============================================================================
; CallForge AI Agent: {name}
; Extension hint: {ext}  |  AudioSocket: {audio_host}:{port}
; Paste into FreePBX → Admin → Config Edit → extensions_custom.conf
; Then create a Custom Destination pointing to: callforge-agent-{ext},s,1
; =============================================================================
[callforge-agent-{ext}]
exten => s,1,NoOp(CallForge Method 1 AudioSocket → {name})
 same => n,Answer()
 same => n,Set(CALL_UUID=${{UUID()}})
 same => n,NoOp(CallForge Call UUID: ${{CALL_UUID}})
 same => n,Set(CF_AGENT_ID={agent_id})
 same => n,Set(CF_API={base})
 ; Register caller ID with CallForge (works across separate FreePBX host — no shared FS)
 same => n,Set(CF_REG=${{CURL(${{CF_API}}/api/telephony/session?call_uuid=${{CALL_UUID}}&caller_id=${{CALLERID(num)}}&agent_id={agent_id})}})
 ; Direct raw PCM AudioSocket — ultra-low latency, instant barge-in
 same => n,AudioSocket(${{CALL_UUID}},{audio_host}:{port})
 ; After AudioSocket ends: human handoff or hangup
 same => n,Set(TARGET=${{CURL(${{CF_API}}/api/telephony/handoff/${{CALL_UUID}})}})
 same => n,GotoIf($["${{TARGET}}" != ""]?do_handoff:do_hangup)
 same => n(do_handoff),NoOp(CallForge handoff → ${{TARGET}} (default {handoff_ext}))
 same => n,Goto({handoff_context},${{TARGET}},1)
 same => n(do_hangup),Hangup()

exten => s,n,NoOp(CallForge AudioSocket failed for {name})
 same => n,Playback(tt-somethingwrong)
 same => n,Hangup()

; Optional: dial internal Custom Extension {ext} from FreePBX phones
exten => {ext},1,Goto(callforge-agent-{ext},s,1)

"""


def render_freepbx_bundle(
    agents: list[AgentRecord],
    host: str | None = None,
    api_base: str | None = None,
) -> str:
    """Full extensions_custom.conf fragment for all deployed agents."""
    audio_host = host or DEFAULT_HOST
    base = _api_base(audio_host, api_base)
    header = f"""\
; AUTO-GENERATED by CallForge — FreePBX Method 1 (Direct AudioSocket)
; =====================================================================
; RECOMMENDED: FreePBX connects directly to CallForge over AudioSocket.
; Do NOT trunk FreePBX → CallForge Asterisk (Method 2) unless FreePBX is
; older than Asterisk 16.14 and lacks res_audiosocket.
;
; Setup (once):
;   1. Deploy agents in CallForge UI (each gets a TCP port 9092+)
;   2. Append this file to FreePBX: /etc/asterisk/extensions_custom.conf
;   3. FreePBX Admin → Apply Config  (or: asterisk -rx "dialplan reload")
;   4. Admin → Custom Destinations → add destination: callforge-agent-XXXX,s,1
;   5. Point Inbound Routes / IVR options at that Custom Destination
;
; CallForge host (AudioSocket): {audio_host}
; CallForge API base:           {base}
; Firewall: allow FreePBX → CallForge TCP 8080 (API) + 9092-9101 (AudioSocket)
; =====================================================================

"""
    deployed = [a for a in agents if a.status == "deployed" and a.port]
    if not deployed:
        return header + "; (no deployed agents — deploy an agent in CallForge first)\n"

    body = header
    body += "; =====================================================================\n"
    body += "; Allow dialing AI agent extensions directly from internal phones/softphones\n"
    body += "; =====================================================================\n"
    body += "[from-internal-custom]\n"
    for agent in sorted(deployed, key=lambda a: a.extension):
        ext = agent.extension.strip()
        body += f"exten => {ext},1,Goto(callforge-agent-{ext},s,1)\n"
    body += "\n"

    for agent in sorted(deployed, key=lambda a: a.extension):
        body += render_agent_freepbx_context(agent, host=audio_host, api_base=base)
    return body


def write_freepbx_dialplan(
    agents: list[AgentRecord],
    output_path: Path,
    host: str | None = None,
    api_base: str | None = None,
) -> Path:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render_freepbx_bundle(agents, host=host, api_base=api_base), encoding="utf-8")
    return output_path


